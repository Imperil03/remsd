const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { spawnSync } = require("node:child_process");
const { createHash } = require("node:crypto");
const { details, requisiteRows, bankRows, cardHash } = require("./lib/contact-details");
const root = path.resolve(__dirname, "..");
const site = require("../src/data/site-config.json").site;
const work = path.join(root, "test-results/contact-card");
const output = path.join(root, "assets/documents/remsd-requisites.pdf");
fs.mkdirSync(work, { recursive: true });
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(path.join(work, "data.json"), JSON.stringify({ rows: requisiteRows(site), banks: details.organization.banks.map((bank) => ({ name: bank.name, rows: bankRows(bank) })), phone: site.phone, email: site.email }));
const bundled = path.join(os.homedir(), ".cache/codex-runtimes/codex-primary-runtime/dependencies/python/python.exe");
const python = process.env.CONTACTS_PYTHON || (fs.existsSync(bundled) ? bundled : process.platform === "win32" ? "python" : "python3");
const result = spawnSync(python, [path.join(__dirname, "render-contact-card.py"), path.join(work, "data.json"), output, path.join(root, "assets/img/logo-remsd.png"), work], { stdio: "inherit" });
if (result.error || result.status !== 0) throw result.error || new Error(`PDF generator failed: ${result.status}`);
const pdfHash = createHash("sha256").update(fs.readFileSync(output)).digest("hex");
fs.writeFileSync(path.join(root, "src/data/contact-card-manifest.json"), JSON.stringify({ sourceHash: cardHash(site), pdfHash }, null, 2) + "\n");
console.log("Contact PDF and preview generated; source fingerprint updated.");
